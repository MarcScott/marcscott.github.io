// Item catalogue for the party inventory app.
//
//   n = name, c = category, w = weight in lb, v = value in cp, d = details
//
// Three sources, all parsed from digital text and diffed against the originals — never
// from the scanned PDFs, whose OCR shreds table columns and mangles numbers:
//
//   Player's Handbook (2024) ch. 6 "Equipment", pp. 212-234 — weapons, armour, ammunition,
//     adventuring gear, packs, tools, focuses, mounts, tack.
//   Dungeon Master's Guide (2024) ch. 7 "Treasure" — trade bars and trade goods (p. 213),
//     gemstones (p. 214), art objects (p. 219).
//   The D&D Beyond magic item index (dndbeyond.com/magic-items) — name, type, rarity,
//     attunement and base item only. No rules text: look the item up to run it.
//
// Weight 0 means no weight is printed for the item. That is most magic items — the index
// doesn't carry weights — except magic weapons and armour, which inherit the weight of the
// mundane item they are built on. Values for magic items are the DMG's suggested value for
// their rarity (Magic Item Rarities and Values, p. 220), halved for consumables other than
// Spell Scrolls, and 0 for Artifacts and for items whose rarity varies. All of it is
// editable per item in the app.
//
// Values are in copper: 1 GP = 100 CP, 1 SP = 10 CP, 1 EP = 50 CP, 1 PP = 1000 CP.

