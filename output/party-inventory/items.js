// digital-text originals and read back against the books:
//
//   Player's Handbook (2024) chapter 6, "Equipment", pp. 212-234 — weapons, armour,
//   ammunition, adventuring gear, packs, tools, focuses, mounts, tack.
//   Dungeon Master's Guide (2024) chapter 7, "Treasure", pp. 213-219 — trade bars and
//   trade goods (p. 213), gemstones (p. 214), art objects (p. 219).
//
//   n = name, c = category, w = weight in lb, v = value in cp, d = details
//
// Weight 0 means the book prints no weight for the item: "—" in the equipment tables,
// nothing at all for gems ("small, lightweight", DMG p. 214), art objects and livestock.
// Values are in copper: 1 GP = 100 CP, 1 SP = 10 CP, 1 EP = 50 CP, 1 PP = 1000 CP.
//
// Named magic items are not here — the party inventory app treats them as custom items,
// with the DMG's rarity values (p. 220) offered in the custom-item form.

